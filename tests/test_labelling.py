@needs_matlab
class StageCLifecycleTests(unittest.TestCase):
    """Full stage C on a small synthetic study: labels vs truth, gates, idempotency, healing, protections."""

    @classmethod
    def setUpClass(cls):
        cls.work = scratch_root() / "stage_c"
        cls.work.mkdir(exist_ok=True)
        cls.synth_dir = cls.work / "synthetic"
        durations = {"II": 130.0, "preict": 130.0, "postict": 70.0}
        if not (cls.synth_dir / "synthetic_manifest.csv").exists():
            synth.make_dataset(cls.synth_dir, n_participants=8, durations=durations, edge_cases=True)
        cls.manifest = cls.synth_dir / "synthetic_manifest.csv"
        cls.truth = json.loads((cls.synth_dir / "truth" / "truth.json").read_text())

    def stage(self, out_dir: Path, manifest: Path, log_name: str, extra: str = "") -> subprocess.CompletedProcess:
        command = (f"addpath('{q(REPO / 'fsms' / 'matlab')}'); try, "
                   f"r = run_study_hierarchy('{q(manifest)}', '{q(out_dir)}'{extra}); "
                   "catch ME, fprintf('ERRID:%s', ME.identifier); fprintf(newline); rethrow(ME); end")
        return run_matlab(command, self.work / log_name)

    def log(self, name: str) -> str:
        return (self.work / name).read_text(encoding="utf-8", errors="replace")

    def test_lifecycle(self):
        out = self.work / "study_out"
        if out.exists():
            shutil.rmtree(out)          # our own scratch output only
        # 1. first run
        first = self.stage(out, self.manifest, "run1.log")
        self.assertEqual(first.returncode, 0, self.log("run1.log")[-4000:])
        audit = ml.validate_recovery_audit_schema(out / "timestamped_backfits" / "recovery_audit.json")
        fit_labels = list(ml.fit_labels_from_recovery_audit(audit))
        self.assertEqual(ml.load_global_labels(out / "hierarchy"), tuple(fit_labels))
        self.assertEqual(ml.load_label_source(out / "hierarchy"), ml.PRESPECIFIED_RULE_ID)
        ml.validate_labelling_audit(out / "hierarchy" / "global" / "labelling_audit.json")
        self.assertEqual(ml.labelling_quality_from_recovery_audit(audit), ("ok", ()))
        # recovered labels equal the generating labels (independent of the template rule)
        generating, correlation = checks.labels_from_generating_maps(out / "hierarchy", self.truth)
        self.assertEqual(fit_labels, generating)
        self.assertGreater(correlation.max(axis=1).min(), 0.8)
        accuracy = checks.peak_label_accuracy(out / "timestamped_backfits", self.synth_dir / "truth", fit_labels)
        # every fitted state's modal generating class is the class the rule gave it (chance level is 1/6; the
        # transition caches hold ALL local GFP maxima, including weak noise peaks, hence the modest accuracy)
        self.assertEqual(accuracy["modal_generating_class_per_state"], fit_labels)
        self.assertGreater(accuracy["accuracy"], 0.6, accuracy["accuracy"])
        self.assertGreater(min(accuracy["per_record"].values()), 0.4)
        # exclusions: SYN09 (too short record) and SYN10 (too little data) excluded with reason codes
        with (out / "exclusions.csv").open(newline="", encoding="utf-8-sig") as handle:
            excluded = {row["participant"]: row["reason_code"] for row in csv.DictReader(handle)}
        self.assertEqual(excluded.get("SYN09"), "RECORD_TOO_FEW_GFP_PEAKS")
        self.assertEqual(excluded.get("SYN10"), "PARTICIPANT_TOO_FEW_GFP_PEAKS")
        self.assertNotIn("SYN11", excluded)
        self.assertEqual(audit["provenance"]["n_excluded_records"], 3)
        with (out / "timestamped_backfits" / "transition_index.csv").open(newline="", encoding="utf-8-sig") as handle:
            index = list(csv.DictReader(handle))
        self.assertTrue({"SYN09", "SYN10"}.isdisjoint({row["participant"] for row in index}))
        # 2. idempotency: re-run skips and changes no file
        before = checks.tree_hashes(out)
        second = self.stage(out, self.manifest, "run2.log")
        self.assertEqual(second.returncode, 0, self.log("run2.log")[-3000:])
        self.assertIn("already complete", self.log("run2.log"))
        self.assertEqual(before, checks.tree_hashes(out))
        # 3. healing: delete one transition cache, re-run, it is rebuilt and the audit stays valid
        caches = sorted((out / "timestamped_backfits" / "transition_cache").glob("*_transitions.mat"))
        victim = caches[len(caches) // 2]
        untouched = {p.name: checks.sha256_file(p) for p in caches if p != victim}
        victim.unlink()
        third = self.stage(out, self.manifest, "run3.log")
        self.assertEqual(third.returncode, 0, self.log("run3.log")[-3000:])
        self.assertTrue(victim.exists())
        ml.validate_recovery_audit_schema(out / "timestamped_backfits" / "recovery_audit.json")
        self.assertEqual(untouched, {p.name: checks.sha256_file(p) for p in caches if p != victim})
        # 4. stale protection: a different manifest must be refused for this folder
        other = self.work / "other_manifest.csv"
        with self.manifest.open(newline="") as handle:
            rows = list(csv.DictReader(handle))
        rows[0]["crop_end_seconds"] = str(float(rows[0]["crop_end_seconds"]) + 1.0)
        with other.open("w", newline="") as handle:
            writer = csv.DictWriter(handle, fieldnames=list(rows[0].keys()))
            writer.writeheader()
            writer.writerows(rows)
        fourth = self.stage(out, other, "run4.log")
        self.assertNotEqual(fourth.returncode, 0)
        self.assertIn("ERRID:FSMS:StaleOutputDir", self.log("run4.log"))

    def test_below_threshold_solution_proceeds_and_is_flagged(self):
        """Unstructured class maps (seed 2: one state at |r| 0.24 to its template) are NOT a stop: the stage
        completes, both gates pass, and the audits carry labelling_quality='below_threshold'."""
        data = self.work / "synthetic_weak_templates"
        if not (data / "synthetic_manifest.csv").exists():
            synth.make_dataset(data, seed=2, n_participants=4, maps_mode="random",
                               durations={"II": 60.0, "preict": 60.0})
        out = self.work / "study_weak_out"
        if out.exists():
            shutil.rmtree(out)
        result = self.stage(out, data / "synthetic_manifest.csv", "run_weak.log")
        self.assertEqual(result.returncode, 0, self.log("run_weak.log")[-3000:])
        self.assertFalse((out / "hierarchy" / "global" / "LABELLING_REJECTED.json").exists())
        self.assertTrue((out / "STAGE_C_DONE.json").exists())
        audit = ml.validate_recovery_audit_schema(out / "timestamped_backfits" / "recovery_audit.json")
        quality, below = ml.labelling_quality_from_recovery_audit(audit)
        self.assertEqual(quality, "below_threshold")
        self.assertTrue(below)
        self.assertIn("nominal", audit["labelling_semantics"])
        absolute = audit["labelling_correlations"]["assigned_abs_r"]
        self.assertEqual(sorted(below), [i + 1 for i, value in enumerate(absolute) if value < 0.5])
        self.assertEqual(ml.load_global_labels(out / "hierarchy"), ml.fit_labels_from_recovery_audit(audit))
        la = ml.validate_labelling_audit(out / "hierarchy" / "global" / "labelling_audit.json")
        self.assertEqual(la["labelling_quality"], "below_threshold")
        self.assertTrue(audit["compact_export_validated_against_full_backfit"])
        self.assertTrue(audit["focused_window_fit_recovery_validation"]["transition_matrix_exact_match"])

    def test_rejection_when_electrode_positions_are_missing(self):
        """No positions and < 16 label matches: the only available match would be first_common_channels."""
        data = self.work / "synthetic_no_positions"
        if not (data / "synthetic_manifest.csv").exists():
            synth.make_dataset(data, n_participants=4, no_positions=True,
                               durations={"II": 90.0, "preict": 90.0})
        out = self.work / "study_no_positions_out"
        if out.exists():
            shutil.rmtree(out)
        result = self.stage(out, data / "synthetic_manifest.csv", "run_no_positions.log")
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("ERRID:FSMS:LabellingRejected", self.log("run_no_positions.log"))
        rejection = out / "hierarchy" / "global" / "LABELLING_REJECTED.json"
        self.assertTrue(rejection.exists())
        evidence = json.loads(rejection.read_text())
        self.assertFalse(evidence["accepted"])
        self.assertIn("CHANNEL_MATCH_MODE_NOT_ALLOWED:first_common_channels", evidence["rejection_reasons"])
        self.assertEqual(evidence["channel_match_mode"], "first_common_channels")
        self.assertFalse((out / "hierarchy" / "global" / "global_manual_labels.csv").exists())
        self.assertFalse((out / "hierarchy" / "global" / "global_manual_labels.mat").exists())
        self.assertFalse((out / "timestamped_backfits" / "recovery_audit.json").exists())
        self.assertTrue((out / "STAGE_C_FAILED.json").exists())
        self.assertFalse((out / "STAGE_C_DONE.json").exists())


