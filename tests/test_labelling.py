def scratch_root() -> Path:
    root = Path(os.environ.get("FSMS_TEST_SCRATCH", tempfile.gettempdir())) / "fsms_labelling_tests"
    assert_unrestricted(root, "test scratch")
    root.mkdir(parents=True, exist_ok=True)
    return root


def q(value) -> str:
    return str(value).replace("'", "''")


def run_matlab(command: str, log: Path, timeout: int = 3600) -> subprocess.CompletedProcess:
    with log.open("w", encoding="utf-8") as handle:
        return subprocess.run([MATLAB, "-batch", command], stdout=handle, stderr=subprocess.STDOUT,
                              timeout=timeout, check=False)


NOMINAL = ("State names are nominal; primary and secondary outcomes do not depend on them; "
           "below_threshold means descriptive per-state names are unreliable.")


def good_labelling_audit(absolute=None) -> dict:
    labels = ["C", "A", "F", "G", "E", "B"]
    classes = list(ml.PRESPECIFIED_CLASSES)
    matrix = [[0.2] * 6 for _ in range(6)]
    absolute = list(absolute or [0.9, 0.95, 0.93, 0.91, 0.92, 0.98])
    below = [{"state_index": i + 1, "label": labels[i], "assigned_abs_r": v}
             for i, v in enumerate(absolute) if v < 0.5]
    for state, label in enumerate(labels):
        matrix[state][classes.index(label)] = absolute[state]
    return {
        "rule_id": ml.PRESPECIFIED_RULE_ID, "accepted": True, "labels_by_fitted_state": labels,
        "assigned_abs_r": absolute, "strong_threshold": 0.5, "correlation_matrix_abs": matrix,
        "correlation_matrix_abs_columns": classes, "channel_match_mode": "coordinates_idw_to_template",
        "template_sha256": "a" * 64, "classes_excluded_a_priori": ["D"],
        "labelling_quality": "below_threshold" if below else "ok", "states_below_threshold": below,
        "nominal_label_semantics": NOMINAL,
    }


def good_recovery_audit(absolute=None) -> dict:
    audit = good_labelling_audit(absolute)
    return {
        "labelling_quality": audit["labelling_quality"],
        "labelling_states_below_threshold": audit["states_below_threshold"], "labelling_semantics": NOMINAL,
        "schema_version": 2, "manifest_sha256": "b" * 64, "fit_labels": audit["labels_by_fitted_state"],
        "manual_labels_by_fitted_state": audit["labels_by_fitted_state"],
        "labelling_rule": ml.PRESPECIFIED_RULE_ID,
        "labelling_correlations": {"assigned_abs_r": audit["assigned_abs_r"]},
        "matlab_version": "25.1.0.0 (R2025a)", "script_fingerprint": "c" * 64,
        "script_sha256": [{"path": "run_vg_microstates.m", "sha256": "d" * 64}],
        "n_timestamped_records": 10, "n_transitions": 1000,
        "compact_export_validated_against_full_backfit": True,
        "focused_window_fit_recovery_validation": {
            "performed": True, "transition_matrix_exact_match": True, "n_windows_checked": 12,
            "n_windows_mismatched": 0},
    }


class LabelValidationTests(unittest.TestCase):
    def test_legacy_validation_still_works(self):
        self.assertEqual(ml.validate_label_order("FEGBAC"), ("F", "E", "G", "B", "A", "C"))
        with self.assertRaises(ValueError):
            ml.validate_label_order("FFGBAC")

